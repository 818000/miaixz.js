/**
 * Converts Lucide's audited iconNode data into the public neutral definition.
 *
 * @param value - Lucide icon-node tuples.
 * @returns A validated neutral SVG definition.
 */
export function fromLucideIconNode(value: unknown): IconSvgDefinition {
  if (!Array.isArray(value)) throw new TypeError("[miaixz] Invalid Lucide icon node.");
  const nodes: IconSvgNode[] = value.map((candidate) => {
    if (
      !Array.isArray(candidate) ||
      candidate.length !== 2 ||
      typeof candidate[0] !== "string" ||
      !candidate[1] ||
      typeof candidate[1] !== "object"
    ) {
      throw new TypeError("[miaixz] Invalid Lucide icon node.");
    }
    const attributes: Record<string, string | number> = {};
    for (const [rawName, rawValue] of Object.entries(candidate[1] as Record<string, unknown>)) {
      if (rawName === "key") continue;
      const name =
        rawName === "fill-rule" ? "fillRule" : rawName === "clip-rule" ? "clipRule" : rawName;
      if (
        !attributeNames.has(name as keyof IconSvgAttributes) ||
        (typeof rawValue !== "string" && typeof rawValue !== "number")
      ) {
        throw new TypeError(`[miaixz] Unsupported Lucide SVG attribute "${rawName}".`);
      }
      attributes[name] = rawValue;
    }
    return { tag: candidate[0] as IconSvgNode["tag"], attributes };
  });
  return assertIconDefinition({
    kind: "svg",
    viewBox: "0 0 24 24",
    paint: "stroke",
    nodes,
  }) as IconSvgDefinition;
}

/**
 * Creates an on-demand loader for one audited Lucide export.
 *
 * @param nativeName - Lucide dynamic-import key.
 * @returns A provider-neutral icon loader.
 */
const loadLucide =
  (nativeName: keyof typeof dynamicIconImports): IconLoader =>
  async () => {
    const module = await dynamicIconImports[nativeName]();
    return { default: fromLucideIconNode(module.__iconNode) };
  };

const icons = Object.fromEntries(
  Object.entries(lucideNativeNames).map(([name, nativeName]) => [name, loadLucide(nativeName)]),
) as Readonly<Record<IconName, IconLoader>>;

const lucideProviderModule: IconProviderModule = Object.freeze({ id: "lucide", icons });

