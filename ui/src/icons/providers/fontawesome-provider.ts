/**
 * Implements the fontawesome provider icon provider integration.
 */

import type { LazyIconProvider } from "../icon-provider.js";

/**
 * Provides the audited Font Awesome Free subset as a lazy provider.
 */
export const fontAwesomeProvider: LazyIconProvider = Object.freeze({
  id: "fontawesome-free",
  dependency: "@fortawesome/free-solid-svg-icons",
  path: ".",
  load: async () => (await import("./fontawesome-module.js")).default,
});
