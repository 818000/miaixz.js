/**
 * Verifies that the source comment policy rejects stacked documentation without rejecting licenses or directives.
 */

import { Linter } from "eslint";
import { describe, expect, it } from "vitest";
/**
 * Loads the shared JavaScript comment policy directly for isolated rule tests.
 * @ts-expect-error The repository policy module has no TypeScript declaration. */
import strictComments from "../../../.github/scripts/quality/enforce-source-policy.mjs";

/**
 * Runs only the repository comment policy against an isolated JavaScript source.
 *
 * @param source - Source text to inspect without applying fixes.
 * @returns Comment-policy diagnostics.
 */
const inspect = (source: string) =>
  new Linter().verify(source, {
    plugins: { miaixz: strictComments },
    rules: { "miaixz/require-jsdoc-comments": "error" },
  });

describe("source comment policy", () => {
  it.each(["\n", "\n\n", " "])("rejects stacked JSDoc separated by %j", (separator) => {
    const source =
      "/**\n * Module description.\n */" +
      separator +
      "/**\n * Declaration description.\n */\nconst value = 1;\n";
    expect(inspect(source).map(({ messageId }) => messageId)).toEqual(["adjacentJsdoc"]);
  });

  it("accepts one combined description and generation notice", () => {
    expect(
      inspect(
        "/**\n * Generated by a generator. Do not edit.\n *\n * Declaration description.\n */\nconst value = 1;\n",
      ),
    ).toEqual([]);
  });

  it("preserves the separate repository license and declaration documentation", () => {
    expect(
      inspect(
        "/*\n * Copyright miaixz.org\n */\n\n/**\n * Declaration description.\n */\nconst value = 1;\n",
      ),
    ).toEqual([]);
  });

  it("allows documentation on separate declarations", () => {
    expect(
      inspect(
        "/**\n * First declaration.\n */\nconst first = 1;\n/**\n * Second declaration.\n */\nconst second = 2;\n",
      ),
    ).toEqual([]);
  });

  it("does not treat branding in later code as part of a leading license", () => {
    expect(
      inspect(
        "/**\n * Module description.\n */\nconst branding = 'miaixz.org';\n/**\n * Declaration description.\n */\nconst value = 1;\n",
      ),
    ).toEqual([]);
  });

  it("preserves a justified TypeScript directive in a combined comment", () => {
    expect(
      inspect(
        "/**\n * Shared JavaScript tool.\n *\n * @ts-expect-error The tool has no declaration. */\nimport tool from 'tool';\n",
      ),
    ).toEqual([]);
  });
});
