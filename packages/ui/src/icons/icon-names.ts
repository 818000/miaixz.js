/**
 * Defines the only public icon-name type.
 */
export type IconName = (typeof ICON_NAMES)[keyof typeof ICON_NAMES];

/**
 * Describes one stable standard name without supplier metadata.
 */
export interface IconCatalogEntry {
  readonly description: string;
}

/**
 * Derives the public catalog from the single icon-name definition.
 */
export const iconCatalog = Object.freeze(
  Object.fromEntries(
    Object.values(ICON_NAMES).map((name) => [name, Object.freeze({ description: name })]),
  ),
) as Readonly<Record<IconName, IconCatalogEntry>>;

const iconNameSet = new Set<string>(Object.values(ICON_NAMES));

/**
 * Returns whether an unknown value is a public Miaixz icon name.
 *
 * @param value - Unknown value to inspect.
 * @returns Whether the value belongs to the closed name catalog.
 */
export const isIconName = (value: unknown): value is IconName =>
  typeof value === "string" && iconNameSet.has(value);

/**
 * Configures external icon-name parsing.
 */
export interface ParseIconNameOptions {
  readonly fallback?: IconName;
  readonly onInvalid?: (value: unknown) => void;
}

/**
 * Parses external data without weakening the closed IconName type.
 *
 * @param value - External value to parse.
 * @param options - Fallback and invalid-value callback.
 * @returns A valid standard icon name.
 */
export function parseIconName(value: unknown, options: ParseIconNameOptions = {}): IconName {
  if (isIconName(value)) return value;
  options.onInvalid?.(value);
  return options.fallback ?? ICON_NAMES.HELP;
}
