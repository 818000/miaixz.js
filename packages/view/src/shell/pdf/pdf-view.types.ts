/**
 * Defines the public properties of the PDF preview adapter.
 */

import type { FileViewProps } from "../../shell/file/file-view.types.js";

/**
 * Configures the self-hosted PDF specialization of FileView.
 */
type PdfProps<T> = T extends unknown
  ? Omit<T, "mimeType" | "name"> & { readonly name?: string }
  : never;

export type PdfViewProps = PdfProps<FileViewProps>;
